const cache = new Map();
export function icon(name, cls = '') {
  const key = name + '|' + cls;
  if (cache.has(key)) return cache.get(key);
  const bm = BITMAPS[name] || BITMAPS.doc;
  let rects = '';
  bm.forEach((row, y) => {
    let x = 0;
    while (x < 8) {
      if (row[x] === '#') {
        let w = 1;
        while (x + w < 8 && row[x + w] === '#') w++;
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      } else x++;
    }
  });
  const svg = `<svg class="px-icon ${cls}" viewBox="0 0 8 8" aria-hidden="true" shape-rendering="crispEdges" fill="currentColor">${rects}</svg>`;
  cache.set(key, svg);
  return svg;
}

export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach(el => {
    if (!el.dataset.iconDone) {
      el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon));
      el.dataset.iconDone = '1';
    }
  });
}
